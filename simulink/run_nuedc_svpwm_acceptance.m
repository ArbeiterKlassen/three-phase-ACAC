function [results, artifacts] = run_nuedc_svpwm_acceptance( ...
    load_current_sweep_A, input_voltage_sweep_V, varargin)
%RUN_NUEDC_SVPWM_ACCEPTANCE Run the required AC-AC acceptance matrix.
%
% This function never saves or modifies the SLX file. It runs:
%   1) 36 V input, 60 Hz output, 2 A load;
%   2) 36 V input, 30 Hz output, caller-specified load-current sweep;
%   3) caller-specified input-voltage sweep, 30 Hz output, 2 A load.
% Set 'NominalOnly', true with two empty sweep vectors to run only item 1
% without assuming unspecified sweep increments.
%
% The sweep vectors are intentionally required because the problem
% statement gives ranges but does not define their increments.
% RMS and THD use an integer-cycle final window. THD includes harmonics
% 2:MaxHarmonic at the commanded fundamental; reported frequency comes
% from smoothed rising zero crossings of each logged line voltage.

if nargin < 2
    error('NUEDC:Acceptance:SweepRequired', ...
        ['Both load_current_sweep_A and input_voltage_sweep_V are ' ...
         'required. Supply the agreed sweep points explicitly.']);
end

parser = inputParser;
parser.FunctionName = mfilename;
addParameter(parser, 'NominalOnly', false, ...
    @(x) islogical(x) && isscalar(x));
addParameter(parser, 'OutputDirectory', '', ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
addParameter(parser, 'ModelFile', '', ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
addParameter(parser, 'SettlingTime_s', 1.5, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
addParameter(parser, 'MeasurementCycles', 10, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && ...
    x >= 2 && x == floor(x));
addParameter(parser, 'SamplesPerCycle', 2048, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && ...
    x >= 256 && x == floor(x));
addParameter(parser, 'MaxHarmonic', 50, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && ...
    x >= 2 && x == floor(x));
addParameter(parser, 'RmsTarget_V', 32, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(parser, 'RmsTolerance_V', 0.05, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(parser, 'ThdLimit_pct', 1.5, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(parser, 'FrequencyTolerance_Hz', 0.2, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
addParameter(parser, 'PfLimit', 0.98, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && ...
    x > 0 && x <= 1);
addParameter(parser, 'EfficiencyLimit_pct', 95, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && ...
    x > 0 && x <= 100);
addParameter(parser, 'RegulationLimit_pct', 0.3, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0);
parse(parser, varargin{:});
config = parser.Results;

if config.NominalOnly
    if ~isempty(load_current_sweep_A) || ...
            ~isempty(input_voltage_sweep_V)
        error('NUEDC:Acceptance:NominalOnlySweepConflict', ...
            ['NominalOnly=true requires two empty sweep vectors so ' ...
             'caller-supplied points are not silently ignored.']);
    end
    load_current_sweep_A = zeros(0, 1);
    input_voltage_sweep_V = zeros(0, 1);
else
    validate_sweep(load_current_sweep_A, [0.2 2], ...
        'load_current_sweep_A', 'A');
    validate_sweep(input_voltage_sweep_V, [31 41], ...
        'input_voltage_sweep_V', 'V');
end

scriptDir = fileparts(mfilename('fullpath'));
if isempty(config.ModelFile)
    modelFile = fullfile(scriptDir, 'NUEDC2026A_SVPWM.slx');
else
    modelFile = char(config.ModelFile);
    if ~isfile(modelFile)
        modelFile = fullfile(scriptDir, modelFile);
    end
end
if ~isfile(modelFile)
    error('NUEDC:Acceptance:ModelMissing', ...
        ['Acceptance model not found: %s\nRun ' ...
         'modify_nuedc_svpwm only after model-overwrite approval.'], ...
        modelFile);
end
if isempty(config.OutputDirectory)
    config.OutputDirectory = fullfile( ...
        scriptDir, 'acceptance_results');
else
    config.OutputDirectory = char(config.OutputDirectory);
end

load_current_sweep_A = unique( ...
    double(load_current_sweep_A(:)), 'stable');
input_voltage_sweep_V = unique( ...
    double(input_voltage_sweep_V(:)), 'stable');
cases = build_cases(load_current_sweep_A, input_voltage_sweep_V);

[~, mdl] = fileparts(modelFile);
modelWasLoaded = bdIsLoaded(mdl);
if modelWasLoaded && strcmp(get_param(mdl, 'Dirty'), 'on')
    error('NUEDC:Acceptance:DirtyModel', ...
        ['Model %s has unsaved edits. Save or close it before a ' ...
         'traceable acceptance run.'], mdl);
end
load_system(modelFile);
modelCleanup = onCleanup(@() close_model_if_owned( ...
    mdl, modelWasLoaded));

requiredLogs = { ...
    'output_v_ab', 'output_v_bc', 'output_v_ca', 'v_dc', ...
    'input_pf', 'rect_mod_saturated', 'svpwm_saturated', ...
    'efficiency_percent', 'loss_model_valid'};
rows = repmat(empty_result_row(), height(cases), 1);

for k = 1:height(cases)
    stopTime = config.SettlingTime_s + ...
        config.MeasurementCycles / cases.FoutCommand_Hz(k);
    simIn = Simulink.SimulationInput(mdl);
    simIn = setVariable(simIn, 'Ui_rms', cases.UiRms_V(k), ...
        'Workspace', mdl);
    simIn = setVariable(simIn, 'f_out', ...
        cases.FoutCommand_Hz(k), 'Workspace', mdl);
    simIn = setVariable(simIn, 'Io_rms', cases.IoRms_A(k), ...
        'Workspace', mdl);
    simIn = setVariable(simIn, 'Ull_rms', ...
        config.RmsTarget_V, 'Workspace', mdl);
    simIn = setModelParameter(simIn, ...
        'StopTime', sprintf('%.17g', stopTime), ...
        'SimulationMode', 'normal', ...
        'SignalLogging', 'on', ...
        'SignalLoggingName', 'logsout', ...
        'ReturnWorkspaceOutputs', 'on');

    try
        simOut = sim(simIn);
        logs = require_logsout(simOut, requiredLogs, k, cases);
        rows(k) = analyze_case(logs, cases(k, :), config, stopTime);
    catch cause
        wrapped = MException('NUEDC:Acceptance:CaseFailed', ...
            ['Acceptance case %d (%s, Ui=%.6g V, f=%.6g Hz, ' ...
             'Io=%.6g A) failed.'], ...
            k, char(cases.CaseGroup(k)), cases.UiRms_V(k), ...
            cases.FoutCommand_Hz(k), cases.IoRms_A(k));
        throwAsCaller(addCause(wrapped, cause));
    end
end

results = struct2table(rows);
summary = summarize_matrix(results, config);
if ~isfolder(config.OutputDirectory)
    mkdir(config.OutputDirectory);
end
stamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss_SSS'));
csvPath = fullfile(config.OutputDirectory, ...
    ['NUEDC2026A_SVPWM_acceptance_' stamp '.csv']);
matPath = fullfile(config.OutputDirectory, ...
    ['NUEDC2026A_SVPWM_acceptance_' stamp '.mat']);
summaryCsvPath = fullfile(config.OutputDirectory, ...
    ['NUEDC2026A_SVPWM_acceptance_summary_' stamp '.csv']);
if isfile(csvPath) || isfile(matPath) || isfile(summaryCsvPath)
    error('NUEDC:Acceptance:OutputExists', ...
        'Refusing to overwrite an existing acceptance artifact.');
end
writetable(results, csvPath);
writetable(struct2table(summary), summaryCsvPath);
save(matPath, 'results', 'summary', 'cases', 'config');

artifacts = struct( ...
    'csv', csvPath, ...
    'summaryCsv', summaryCsvPath, ...
    'mat', matPath);
fprintf('Acceptance results: %s\n', csvPath);
fprintf('Acceptance summary: %s\n', summaryCsvPath);
fprintf('Acceptance data:    %s\n', matPath);
if any(~results.LossModelValid)
    warning('NUEDC:Acceptance:LossModelInvalid', ...
        ['At least one case has loss_model_valid=false. Efficiency is ' ...
         'reported but AcceptancePass remains false for those cases.']);
end
end

function validate_sweep(values, bounds, name, unit)
if isempty(values)
    error('NUEDC:Acceptance:EmptySweep', ...
        '%s must contain explicit sweep points.', name);
end
validateattributes(values, {'numeric'}, ...
    {'vector', 'real', 'finite', 'nonempty'}, mfilename, name);
values = double(values(:));
if any(values < bounds(1) | values > bounds(2))
    error('NUEDC:Acceptance:SweepOutOfRange', ...
        '%s points must remain within %.6g-%.6g %s.', ...
        name, bounds(1), bounds(2), unit);
end
if ~any(abs(values - bounds(1)) <= 10 * eps(bounds(1))) || ...
        ~any(abs(values - bounds(2)) <= 10 * eps(bounds(2)))
    error('NUEDC:Acceptance:SweepEndpointsMissing', ...
        '%s must explicitly include both %.6g and %.6g %s endpoints.', ...
        name, bounds(1), bounds(2), unit);
end
end

function cases = build_cases(loadSweep, voltageSweep)
nLoad = numel(loadSweep);
nVoltage = numel(voltageSweep);
caseId = (1:(1 + nLoad + nVoltage)).';
caseGroup = [ ...
    "nominal"; ...
    repmat("load_sweep", nLoad, 1); ...
    repmat("input_voltage_sweep", nVoltage, 1)];
ui = [36; repmat(36, nLoad, 1); voltageSweep];
fout = [60; repmat(30, nLoad + nVoltage, 1)];
io = [2; loadSweep; repmat(2, nVoltage, 1)];
cases = table(caseId, caseGroup, ui, fout, io, ...
    'VariableNames', {'CaseId', 'CaseGroup', 'UiRms_V', ...
    'FoutCommand_Hz', 'IoRms_A'});
end

function logs = require_logsout(simOut, requiredNames, caseIndex, cases)
try
    logs = get(simOut, 'logsout');
catch cause
    error('NUEDC:Acceptance:LogsoutMissing', ...
        'Case %d (%s) returned no logsout dataset. Original error: %s', ...
        caseIndex, char(cases.CaseGroup(caseIndex)), cause.message);
end
if isempty(logs) || ...
        ~isa(logs, 'Simulink.SimulationData.Dataset')
    error('NUEDC:Acceptance:LogsoutMissing', ...
        'Case %d (%s) did not return a Simulink logsout dataset.', ...
        caseIndex, char(cases.CaseGroup(caseIndex)));
end
for k = 1:numel(requiredNames)
    try
        element = getElement(logs, requiredNames{k});
    catch
        element = [];
    end
    if isempty(element)
        error('NUEDC:Acceptance:RequiredSignalMissing', ...
            ['Case %d (%s) logsout is missing required signal "%s". ' ...
             'Do not interpret this run as passing.'], ...
            caseIndex, char(cases.CaseGroup(caseIndex)), ...
            requiredNames{k});
    end
end
end

function row = analyze_case(logs, caseRow, config, stopTime)
tStart = stopTime - ...
    config.MeasurementCycles / caseRow.FoutCommand_Hz;
vab = waveform_metrics(logs, 'output_v_ab', tStart, stopTime, ...
    caseRow.FoutCommand_Hz, config);
vbc = waveform_metrics(logs, 'output_v_bc', tStart, stopTime, ...
    caseRow.FoutCommand_Hz, config);
vca = waveform_metrics(logs, 'output_v_ca', tStart, stopTime, ...
    caseRow.FoutCommand_Hz, config);

[vdcTime, vdc] = logged_vector(logs, 'v_dc');
vdcWindow = window_values(vdcTime, vdc, tStart, stopTime, 'v_dc');
vdcMean = mean(vdcWindow);
vdcRipple = max(vdcWindow) - min(vdcWindow);
if abs(vdcMean) <= eps
    error('NUEDC:Acceptance:ZeroVdcMean', ...
        'Mean DC-link voltage is zero; ripple percentage is undefined.');
end

inputPf = window_mean(logs, 'input_pf', tStart, stopTime);
rectSat = 100 * window_mean( ...
    logs, 'rect_mod_saturated', tStart, stopTime);
svpwmSat = 100 * window_mean( ...
    logs, 'svpwm_saturated', tStart, stopTime);
efficiency = window_mean( ...
    logs, 'efficiency_percent', tStart, stopTime);
lossValidMean = window_mean( ...
    logs, 'loss_model_valid', tStart, stopTime);
lossValid = isfinite(lossValidMean) && lossValidMean >= 1;

rmsValues = [vab.rms vbc.rms vca.rms];
thdValues = [vab.thdPct vbc.thdPct vca.thdPct];
frequencyValues = [vab.frequency vbc.frequency vca.frequency];
rmsPass = all(abs(rmsValues - config.RmsTarget_V) <= ...
    config.RmsTolerance_V);
thdPass = all(thdValues <= config.ThdLimit_pct);
frequencyPass = all(abs(frequencyValues ...
    - caseRow.FoutCommand_Hz) <= config.FrequencyTolerance_Hz);
pfPass = inputPf >= config.PfLimit;
efficiencyPass = lossValid ...
    && efficiency >= config.EfficiencyLimit_pct;
electricalPass = rmsPass && thdPass && frequencyPass && pfPass;

row = empty_result_row();
row.CaseId = caseRow.CaseId;
row.CaseGroup = caseRow.CaseGroup;
row.UiRms_V = caseRow.UiRms_V;
row.FoutCommand_Hz = caseRow.FoutCommand_Hz;
row.IoRms_A = caseRow.IoRms_A;
row.VabRms_V = vab.rms;
row.VbcRms_V = vbc.rms;
row.VcaRms_V = vca.rms;
row.VabFrequency_Hz = vab.frequency;
row.VbcFrequency_Hz = vbc.frequency;
row.VcaFrequency_Hz = vca.frequency;
row.VabThd_pct = vab.thdPct;
row.VbcThd_pct = vbc.thdPct;
row.VcaThd_pct = vca.thdPct;
row.InputPF = inputPf;
row.VdcMean_V = vdcMean;
row.VdcRipplePkPk_V = vdcRipple;
row.VdcRipple_pct = 100 * vdcRipple / abs(vdcMean);
row.RectSaturation_pct = rectSat;
row.SvpwmSaturation_pct = svpwmSat;
row.Efficiency_pct = efficiency;
row.LossModelValid = lossValid;
row.VoltageRmsPass = rmsPass;
row.VoltageThdPass = thdPass;
row.FrequencyPass = frequencyPass;
row.InputPfPass = pfPass;
row.EfficiencyPass = efficiencyPass;
row.ElectricalThresholdsPass = electricalPass;
row.AcceptancePass = electricalPass && efficiencyPass;
end

function summary = summarize_matrix(results, config)
loadLow = find_case(results, "load_sweep", ...
    'IoRms_A', 0.2);
loadHigh = find_case(results, "load_sweep", ...
    'IoRms_A', 2);
inputLow = find_case(results, "input_voltage_sweep", ...
    'UiRms_V', 31);
inputHigh = find_case(results, "input_voltage_sweep", ...
    'UiRms_V', 41);
matrixComplete = ~isempty(loadLow) && ~isempty(loadHigh) ...
    && ~isempty(inputLow) && ~isempty(inputHigh);

summary = struct( ...
    'MatrixComplete', matrixComplete, ...
    'LoadRegulationVab_pct', NaN, ...
    'LoadRegulationVbc_pct', NaN, ...
    'LoadRegulationVca_pct', NaN, ...
    'LoadRegulationWorst_pct', NaN, ...
    'LoadRegulationPass', false, ...
    'InputRegulationVab_pct', NaN, ...
    'InputRegulationVbc_pct', NaN, ...
    'InputRegulationVca_pct', NaN, ...
    'InputRegulationWorst_pct', NaN, ...
    'InputRegulationPass', false, ...
    'AllCaseThresholdsPass', all(results.AcceptancePass), ...
    'OverallPass', false);
if ~matrixComplete
    return;
end

loadAtLow = [loadLow.VabRms_V loadLow.VbcRms_V loadLow.VcaRms_V];
loadAtHigh = [loadHigh.VabRms_V loadHigh.VbcRms_V loadHigh.VcaRms_V];
inputAtLow = [inputLow.VabRms_V inputLow.VbcRms_V inputLow.VcaRms_V];
inputAtHigh = [inputHigh.VabRms_V inputHigh.VbcRms_V inputHigh.VcaRms_V];
loadRegulation = 100 * abs(loadAtHigh - loadAtLow) ./ abs(loadAtLow);
inputRegulation = 100 * abs(inputAtHigh - inputAtLow) ...
    / config.RmsTarget_V;

summary.LoadRegulationVab_pct = loadRegulation(1);
summary.LoadRegulationVbc_pct = loadRegulation(2);
summary.LoadRegulationVca_pct = loadRegulation(3);
summary.LoadRegulationWorst_pct = max(loadRegulation);
summary.LoadRegulationPass = ...
    summary.LoadRegulationWorst_pct <= config.RegulationLimit_pct;
summary.InputRegulationVab_pct = inputRegulation(1);
summary.InputRegulationVbc_pct = inputRegulation(2);
summary.InputRegulationVca_pct = inputRegulation(3);
summary.InputRegulationWorst_pct = max(inputRegulation);
summary.InputRegulationPass = ...
    summary.InputRegulationWorst_pct <= config.RegulationLimit_pct;
summary.OverallPass = summary.AllCaseThresholdsPass ...
    && summary.LoadRegulationPass && summary.InputRegulationPass;
end

function row = find_case(results, group, variable, target)
mask = results.CaseGroup == group ...
    & abs(results.(variable) - target) <= 10 * eps(target);
row = results(mask, :);
if height(row) > 1
    error('NUEDC:Acceptance:DuplicateEndpoint', ...
        'Multiple %s rows match endpoint %.6g.', variable, target);
end
end

function metrics = waveform_metrics( ...
    logs, signalName, tStart, tStop, nominalFrequency, config)
[time, data] = logged_vector(logs, signalName);
if time(1) > tStart || time(end) < tStop
    error('NUEDC:Acceptance:InsufficientLogWindow', ...
        ['Signal "%s" does not cover the required %.6g-%.6g s ' ...
         'measurement window.'], signalName, tStart, tStop);
end

samplesPerCycle = config.SamplesPerCycle;
sampleCount = config.MeasurementCycles * samplesPerCycle;
queryTime = tStart + ...
    (0:(sampleCount - 1)).' / (nominalFrequency * samplesPerCycle);
waveform = interp1(time, data, queryTime, 'linear');
if any(~isfinite(waveform))
    error('NUEDC:Acceptance:NonfiniteWaveform', ...
        'Signal "%s" contains nonfinite values.', signalName);
end

ac = waveform - mean(waveform);
sampleIndex = (0:(sampleCount - 1)).';
maxHarmonic = min(config.MaxHarmonic, ...
    floor(samplesPerCycle / 2) - 1);
harmonicRms = zeros(maxHarmonic, 1);
for h = 1:maxHarmonic
    coefficient = (2 / sampleCount) * sum(ac .* exp( ...
        -1i * 2 * pi * h * sampleIndex / samplesPerCycle));
    harmonicRms(h) = abs(coefficient) / sqrt(2);
end
if harmonicRms(1) <= eps
    error('NUEDC:Acceptance:FundamentalMissing', ...
        'Signal "%s" has no measurable fundamental.', signalName);
end

smoothed = movmean(ac, max(3, round(samplesPerCycle / 20)));
crossings = find(smoothed(1:end-1) <= 0 & smoothed(2:end) > 0);
if numel(crossings) < 2
    error('NUEDC:Acceptance:FrequencyUnavailable', ...
        'Signal "%s" has too few rising zero crossings.', signalName);
end
fraction = -smoothed(crossings) ./ ...
    (smoothed(crossings + 1) - smoothed(crossings));
crossingTime = queryTime(crossings) + fraction ./ ...
    (nominalFrequency * samplesPerCycle);
periods = diff(crossingTime);
periods = periods(isfinite(periods) & periods > 0);
if isempty(periods)
    error('NUEDC:Acceptance:FrequencyUnavailable', ...
        'Signal "%s" has invalid zero-crossing periods.', signalName);
end

metrics = struct( ...
    'rms', sqrt(mean(waveform .^ 2)), ...
    'frequency', 1 / median(periods), ...
    'thdPct', 100 * sqrt(sum(harmonicRms(2:end) .^ 2)) / ...
        harmonicRms(1));
end

function value = window_mean(logs, signalName, tStart, tStop)
[time, data] = logged_vector(logs, signalName);
values = window_values(time, data, tStart, tStop, signalName);
value = mean(values);
if ~isfinite(value)
    error('NUEDC:Acceptance:NonfiniteMetric', ...
        'Signal "%s" produced a nonfinite mean.', signalName);
end
end

function values = window_values(time, data, tStart, tStop, signalName)
mask = time >= tStart & time <= tStop;
values = data(mask);
if isempty(values) && isscalar(time) && time(1) <= tStop
    values = data;
end
if isempty(values)
    error('NUEDC:Acceptance:InsufficientLogWindow', ...
        'Signal "%s" has no samples in %.6g-%.6g s.', ...
        signalName, tStart, tStop);
end
values = values(isfinite(values));
if isempty(values)
    error('NUEDC:Acceptance:NonfiniteMetric', ...
        'Signal "%s" has no finite samples in the measurement window.', ...
        signalName);
end
end

function [time, data] = logged_vector(logs, signalName)
element = getElement(logs, signalName);
values = element.Values;
if ~isa(values, 'timeseries')
    error('NUEDC:Acceptance:UnsupportedLogType', ...
        'Signal "%s" must be logged as a timeseries.', signalName);
end
time = double(values.Time(:));
data = squeeze(double(values.Data));
if ~isvector(data) || numel(data) ~= numel(time)
    error('NUEDC:Acceptance:UnsupportedSignalShape', ...
        'Signal "%s" must be scalar-valued.', signalName);
end
data = data(:);
[time, uniqueIndices] = unique(time, 'stable');
data = data(uniqueIndices);
if numel(time) < 1 || any(~isfinite(time))
    error('NUEDC:Acceptance:InvalidTimeVector', ...
        'Signal "%s" has an invalid time vector.', signalName);
end
end

function row = empty_result_row()
row = struct( ...
    'CaseId', 0, ...
    'CaseGroup', "", ...
    'UiRms_V', NaN, ...
    'FoutCommand_Hz', NaN, ...
    'IoRms_A', NaN, ...
    'VabRms_V', NaN, ...
    'VbcRms_V', NaN, ...
    'VcaRms_V', NaN, ...
    'VabFrequency_Hz', NaN, ...
    'VbcFrequency_Hz', NaN, ...
    'VcaFrequency_Hz', NaN, ...
    'VabThd_pct', NaN, ...
    'VbcThd_pct', NaN, ...
    'VcaThd_pct', NaN, ...
    'InputPF', NaN, ...
    'VdcMean_V', NaN, ...
    'VdcRipplePkPk_V', NaN, ...
    'VdcRipple_pct', NaN, ...
    'RectSaturation_pct', NaN, ...
    'SvpwmSaturation_pct', NaN, ...
    'Efficiency_pct', NaN, ...
    'LossModelValid', false, ...
    'VoltageRmsPass', false, ...
    'VoltageThdPass', false, ...
    'FrequencyPass', false, ...
    'InputPfPass', false, ...
    'EfficiencyPass', false, ...
    'ElectricalThresholdsPass', false, ...
    'AcceptancePass', false);
end

function close_model_if_owned(mdl, modelWasLoaded)
if ~modelWasLoaded && bdIsLoaded(mdl)
    close_system(mdl, 0);
end
end
