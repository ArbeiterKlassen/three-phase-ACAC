    'ExternalReset', 'level', ...
    'InitialCondition', '0', ...
    'SampleTime', 'Ts_ctrl', ...
    'LimitOutput', 'on', ...
    'UpperSaturationLimit', '1', ...
    'LowerSaturationLimit', '0', ...
    'Position', [690 1140 750 1200]);

vdcSafetyPorts = get_param(vdcSafetyFrom, 'PortHandles');
rectThresholdPorts = get_param(rectThreshold, 'PortHandles');
invThresholdPorts = get_param(invThreshold, 'PortHandles');
rectValidPorts = get_param(rectValid, 'PortHandles');
invValidPorts = get_param(invValid, 'PortHandles');
rectInvalidPorts = get_param(rectInvalid, 'PortHandles');
invInvalidPorts = get_param(invInvalid, 'PortHandles');
softStartRatePorts = get_param(softStartRate, 'PortHandles');
rectEnablePorts = get_param(rectEnable, 'PortHandles');
invEnablePorts = get_param(invEnable, 'PortHandles');
add_line(mdl, vdcSafetyPorts.Outport(1), rectValidPorts.Inport(1), ...
    'autorouting', 'on');
add_line(mdl, rectThresholdPorts.Outport(1), rectValidPorts.Inport(2), ...
    'autorouting', 'on');
add_line(mdl, vdcSafetyPorts.Outport(1), invValidPorts.Inport(1), ...
    'autorouting', 'on');
add_line(mdl, invThresholdPorts.Outport(1), invValidPorts.Inport(2), ...
    'autorouting', 'on');
add_line(mdl, rectValidPorts.Outport(1), ...
    rectInvalidPorts.Inport(1), 'autorouting', 'on');
add_line(mdl, invValidPorts.Outport(1), ...
    invInvalidPorts.Inport(1), 'autorouting', 'on');
add_line(mdl, softStartRatePorts.Outport(1), ...
    rectEnablePorts.Inport(1), 'autorouting', 'on');
add_line(mdl, rectInvalidPorts.Outport(1), ...
    rectEnablePorts.Inport(2), 'autorouting', 'on');
add_line(mdl, softStartRatePorts.Outport(1), ...
    invEnablePorts.Inport(1), 'autorouting', 'on');
add_line(mdl, invInvalidPorts.Outport(1), ...
    invEnablePorts.Inport(2), 'autorouting', 'on');

