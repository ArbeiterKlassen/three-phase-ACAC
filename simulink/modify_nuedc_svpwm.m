function replace_notch_with_discrete(mdl, sid)
oldBlock = sid_handle(mdl, sid);
oldPath = getfullname(oldBlock);
parent = get_param(oldPath, 'Parent');
blockName = get_param(oldPath, 'Name');
position = get_param(oldPath, 'Position');
oldPorts = get_param(oldPath, 'PortHandles');
inputLine = get_param(oldPorts.Inport(1), 'Line');
outputLine = get_param(oldPorts.Outport(1), 'Line');
assert(inputLine ~= -1 && outputLine ~= -1, ...
    'Notch filter must be connected before replacement.');
sourcePort = get_param(inputLine, 'SrcPortHandle');
destinationPorts = get_param(outputLine, 'DstPortHandle');
delete_line(inputLine);
delete_line(outputLine);
delete_block(oldPath);

k = '(notch_w/tan(notch_w*Ts_outer/2))';
a0 = sprintf('(%s^2+notch_bw*%s+notch_w^2)', k, k);
numerator = sprintf( ...
    '[%s^2+notch_w^2 -2*%s^2+2*notch_w^2 %s^2+notch_w^2]/%s', ...
    k, k, k, a0);
denominator = sprintf([ ...
    '[1 (-2*%s^2+2*notch_w^2)/%s ' ...
    '(%s^2-notch_bw*%s+notch_w^2)/%s]'], ...
    k, a0, k, k, a0);
newPath = [parent '/' blockName];
newBlock = add_block('simulink/Discrete/Discrete Transfer Fcn', ...
    newPath, ...
    'Numerator', numerator, ...
    'Denominator', denominator, ...
    'SampleTime', 'Ts_outer', ...
    'Position', position);
newPorts = get_param(newBlock, 'PortHandles');
add_line(parent, sourcePort, newPorts.Inport(1), 'autorouting', 'on');
for kDst = 1:numel(destinationPorts)
    add_line(parent, newPorts.Outport(1), destinationPorts(kDst), ...
        'autorouting', 'on');
end
end

