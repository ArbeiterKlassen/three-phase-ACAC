    vdcTargetDeltaPorts.Inport(1), 'autorouting', 'on');
add_line(mdl, vdcFeedbackPort, ...
    vdcTargetDeltaPorts.Inport(2), 'autorouting', 'on');
add_line(mdl, vdcTargetDeltaPorts.Outport(1), ...
    vdcSoftDeltaPorts.Inport(1), 'autorouting', 'on');
