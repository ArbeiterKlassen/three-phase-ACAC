add_line(mdl, vdcSoftDeltaPorts.Outport(1), ...
    vdcSoftReferencePorts.Inport(2), 'autorouting', 'on');
add_line(mdl, vdcSoftReferencePorts.Outport(1), ...
    vdcErrorPorts.Inport(1), 'autorouting', 'on');

