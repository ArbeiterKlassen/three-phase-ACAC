disconnect_port_line(continuousPorts.Inport(1));
disconnect_port_line(continuousPorts.Outport(1));
delete_block(continuousPath);

% Prewarped bilinear transform of
%   2*Wc*s / (s^2 + 2*Wc*s + Wr^2)
% at the resonant frequency Wr.
k = '(Wr/tan(Wr*Ts_ctrl/2))';
a0 = sprintf('(%s^2+2*Wc*%s+Wr^2)', k, k);
numerator = sprintf('[2*Wc*%s 0 -2*Wc*%s]/%s', k, k, a0);
denominator = sprintf( ...
    '[1 (-2*%s^2+2*Wr^2)/%s (%s^2-2*Wc*%s+Wr^2)/%s]', ...
    k, a0, k, k, a0);
discretePath = [subsystem '/Discrete Resonant'];
discreteBlock = add_block( ...
    'simulink/Discrete/Discrete Transfer Fcn', ...
    discretePath, ...
    'Numerator', numerator, ...
    'Denominator', denominator, ...
    'SampleTime', 'Ts_ctrl', ...
    'ExternalReset', 'Level', ...
    'Position', continuousPosition);
discretePorts = get_param(discreteBlock, 'PortHandles');
add_line(subsystem, krOutput, discretePorts.Inport(1), ...
    'autorouting', 'on');
add_line(subsystem, discretePorts.Outport(1), sumPorts.Inport(2), ...
    'autorouting', 'on');

% Expose a reset request at the subsystem boundary. Also compare the
% pre/post saturation signals already present in each QPR and feed that
% saturation back after one sample. The delay prevents an algebraic loop.
resetIn = add_block('simulink/Ports & Subsystems/In1', ...
    [subsystem '/reset'], ...
    'Port', '2', ...
    'Position', [30 145 60 159]);
qprSaturated = add_block( ...
    'simulink/Logic and Bit Operations/Relational Operator', ...
    [subsystem '/QPR Output Saturated'], ...
    'Operator', '~=', ...
    'Position', [430 105 460 135]);
qprSatDelay = add_block('simulink/Discrete/Unit Delay', ...
    [subsystem '/QPR Saturation Reset Delay'], ...
    'SampleTime', 'Ts_ctrl', ...
    'InitialCondition', 'false', ...
    'Position', [490 105 540 135]);
qprReset = add_block( ...
    'simulink/Logic and Bit Operations/Logical Operator', ...
    [subsystem '/QPR Reset Request'], ...
    'Operator', 'OR', ...
    'Inputs', '2', ...
    'Position', [185 135 215 175]);

resetInPorts = get_param(resetIn, 'PortHandles');
saturationPorts = get_param(saturationPath, 'PortHandles');
qprSaturatedPorts = get_param(qprSaturated, 'PortHandles');
qprSatDelayPorts = get_param(qprSatDelay, 'PortHandles');
qprResetPorts = get_param(qprReset, 'PortHandles');
add_line(subsystem, sumPorts.Outport(1), ...
    qprSaturatedPorts.Inport(1), 'autorouting', 'on');
add_line(subsystem, saturationPorts.Outport(1), ...
    qprSaturatedPorts.Inport(2), 'autorouting', 'on');
add_line(subsystem, qprSaturatedPorts.Outport(1), ...
    qprSatDelayPorts.Inport(1), 'autorouting', 'on');
add_line(subsystem, resetInPorts.Outport(1), ...
    qprResetPorts.Inport(1), 'autorouting', 'on');
add_line(subsystem, qprSatDelayPorts.Outport(1), ...
    qprResetPorts.Inport(2), 'autorouting', 'on');
add_line(subsystem, qprResetPorts.Outport(1), ...
    discretePorts.Inport(2), 'autorouting', 'on');
end

