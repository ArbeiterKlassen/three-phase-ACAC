    'Value', '1/soft_start_time', ...
    'Position', [600 1035 650 1065]);
rectEnable = add_block( ...
    'simulink/Discrete/Discrete-Time Integrator', ...
    [mdl '/Rectifier Soft Enable'], ...
    'IntegratorMethod', 'Integration: Forward Euler', ...
    'gainval', '1.0', ...
    'ExternalReset', 'level', ...
    'InitialCondition', '0', ...
    'SampleTime', 'Ts_outer', ...
    'LimitOutput', 'on', ...
    'UpperSaturationLimit', '1', ...
    'LowerSaturationLimit', '0', ...
    'Position', [690 1070 750 1130]);
invEnable = add_block( ...
    'simulink/Discrete/Discrete-Time Integrator', ...
    [mdl '/Inverter Soft Enable'], ...
    'IntegratorMethod', 'Integration: Forward Euler', ...
