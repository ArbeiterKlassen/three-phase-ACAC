disconnect_port_line(inputPorts.Outport(1));
zoh = add_block('simulink/Discrete/Zero-Order Hold', ...
    [subsystem '/Input ZOH 20 kHz'], ...
    'SampleTime', 'Ts_ctrl', ...
    'Position', [55 75 105 105]);
zohPorts = get_param(zoh, 'PortHandles');
add_line(subsystem, inputPorts.Outport(1), zohPorts.Inport(1), ...
    'autorouting', 'on');
add_line(subsystem, zohPorts.Outport(1), kpPorts.Inport(1), ...
    'autorouting', 'on');
add_line(subsystem, zohPorts.Outport(1), krPorts.Inport(1), ...
    'autorouting', 'on');

continuousPosition = get_param(continuousPath, 'Position');
continuousPorts = get_param(continuousPath, 'PortHandles');
